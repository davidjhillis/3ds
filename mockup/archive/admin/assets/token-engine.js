/**
 * Design Token Engine
 * Converts theme.json → CSS Variables
 *
 * Usage:
 *   const engine = new TokenEngine(themeJSON);
 *   engine.setMode('dark');
 *   engine.injectIntoDOM();
 *
 * @version 1.0.0
 */

class TokenEngine {
  constructor(themeJSON) {
    this.theme = themeJSON || {};
    this.mode = 'light';
    this.resolvedTokens = new Map();
  }

  /**
   * Resolve token references like {color.brand.primary.500}
   * @param {string|any} value - Token value or reference
   * @param {string} type - Token type (color, dimension, etc)
   * @returns {string} Resolved value
   */
  resolveTokenValue(value, type = null) {
    if (typeof value !== 'string') return value;

    // Check if it's a reference (starts with { and ends with })
    const referenceMatch = value.match(/^\{(.+)\}$/);
    if (referenceMatch) {
      const path = referenceMatch[1].split('.');
      let resolved = this.theme.tokens;

      // Navigate the token path
      for (const key of path) {
        resolved = resolved?.[key];
        if (!resolved) {
          console.warn(`Token reference not found: ${value}`);
          return value;
        }
      }

      // Recursively resolve in case the referenced token also contains a reference
      return this.resolveTokenValue(resolved?.value || value, type || resolved?.type);
    }

    // Handle color conversion for Tailwind (hex → space-separated RGB)
    if (type === 'color') {
      return this.hexToRGB(value);
    }

    return value;
  }

  /**
   * Convert hex color to space-separated RGB (for Tailwind CSS variables)
   * @param {string} hex - Hex color code
   * @returns {string} Space-separated RGB values
   */
  hexToRGB(hex) {
    // Remove # if present
    hex = hex.replace('#', '');

    // Handle shorthand hex (e.g., #FFF)
    if (hex.length === 3) {
      hex = hex.split('').map(char => char + char).join('');
    }

    // Parse RGB values
    const result = /^([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);

    if (!result) {
      console.warn(`Invalid hex color: ${hex}`);
      return hex;
    }

    const r = parseInt(result[1], 16);
    const g = parseInt(result[2], 16);
    const b = parseInt(result[3], 16);

    return `${r} ${g} ${b}`;
  }

  /**
   * Flatten nested token object to CSS variable names
   * Example: color.brand.primary.500 → --color-brand-primary-500
   * @param {object} obj - Token object
   * @param {string} prefix - CSS variable prefix
   * @param {object} result - Accumulator for results
   * @returns {object} Flattened tokens map
   */
  flattenTokens(obj, prefix = '', result = {}) {
    if (!obj || typeof obj !== 'object') return result;

    for (const [key, val] of Object.entries(obj)) {
      const newPrefix = prefix ? `${prefix}-${key}` : key;

      // Check if this is a token leaf node (has value and type)
      if (val && typeof val === 'object' && val.value !== undefined && val.type !== undefined) {
        const cssVarName = `--${newPrefix}`;
        const resolvedValue = this.resolveTokenValue(val.value, val.type);
        result[cssVarName] = resolvedValue;
      }
      // Otherwise recurse into nested objects
      else if (val && typeof val === 'object' && !Array.isArray(val)) {
        this.flattenTokens(val, newPrefix, result);
      }
    }

    return result;
  }

  /**
   * Apply mode overrides (e.g., dark mode)
   * @returns {object} Mode-specific tokens
   */
  applyModeOverrides() {
    if (!this.theme.modes || !this.theme.modes[this.mode]) {
      return {};
    }

    return this.flattenTokens(this.theme.modes[this.mode]);
  }

  /**
   * Generate complete CSS string with all variables
   * @returns {string} CSS code
   */
  generateCSS() {
    const baseTokens = this.flattenTokens(this.theme.tokens);
    const modeOverrides = this.applyModeOverrides();

    let css = '/* Generated by Token Engine */\n';
    css += '/* Base theme tokens */\n\n';
    css += ':root {\n';

    for (const [name, value] of Object.entries(baseTokens)) {
      css += `  ${name}: ${value};\n`;
    }

    css += '}\n\n';

    // Add dark mode overrides
    if (this.mode === 'dark' && Object.keys(modeOverrides).length > 0) {
      css += '/* Dark mode overrides */\n\n';
      css += ':root.dark {\n';

      for (const [name, value] of Object.entries(modeOverrides)) {
        css += `  ${name}: ${value};\n`;
      }

      css += '}\n';
    }

    return css;
  }

  /**
   * Inject CSS variables into DOM
   * This is the primary method for applying themes at runtime
   */
  injectIntoDOM() {
    const baseTokens = this.flattenTokens(this.theme.tokens);
    const root = document.documentElement;

    // Apply base tokens
    for (const [name, value] of Object.entries(baseTokens)) {
      root.style.setProperty(name, value);
    }

    // Apply mode-specific overrides
    const modeOverrides = this.applyModeOverrides();
    for (const [name, value] of Object.entries(modeOverrides)) {
      root.style.setProperty(name, value);
    }

    // Apply mode class to <html>
    root.classList.remove('light', 'dark');
    root.classList.add(this.mode);

    console.log(`✅ TokenEngine: Applied ${Object.keys(baseTokens).length} tokens (${this.mode} mode)`);

    // Store in cache for quick access
    this.resolvedTokens.clear();
    for (const [name, value] of Object.entries({ ...baseTokens, ...modeOverrides })) {
      this.resolvedTokens.set(name, value);
    }
  }

  /**
   * Set theme mode (light/dark) and re-apply
   * @param {string} mode - 'light' or 'dark'
   */
  setMode(mode) {
    if (mode !== 'light' && mode !== 'dark') {
      console.warn(`Invalid mode: ${mode}. Using 'light'`);
      mode = 'light';
    }

    this.mode = mode;
    this.injectIntoDOM();

    // Save to localStorage
    try {
      localStorage.setItem('themeMode', mode);
    } catch (e) {
      console.warn('Could not save mode to localStorage:', e);
    }
  }

  /**
   * Get token value by path
   * @param {string} path - Dot-separated path (e.g., 'color.brand.primary.500')
   * @returns {string|null} Token value
   */
  getToken(path) {
    const keys = path.split('.');
    let value = this.theme.tokens;

    for (const key of keys) {
      value = value?.[key];
      if (!value) return null;
    }

    return value?.value || null;
  }

  /**
   * Update token value (for theme editor)
   * @param {string} path - Dot-separated path
   * @param {string} newValue - New token value
   */
  updateToken(path, newValue) {
    const keys = path.split('.');
    let obj = this.theme.tokens;

    // Navigate to parent object
    for (let i = 0; i < keys.length - 1; i++) {
      if (!obj[keys[i]]) {
        console.warn(`Token path not found: ${path}`);
        return false;
      }
      obj = obj[keys[i]];
    }

    const lastKey = keys[keys.length - 1];

    // Update the value
    if (obj[lastKey] && obj[lastKey].value !== undefined) {
      obj[lastKey].value = newValue;
      this.injectIntoDOM(); // Re-apply to DOM
      console.log(`Updated token: ${path} = ${newValue}`);
      return true;
    }

    console.warn(`Token not found: ${path}`);
    return false;
  }

  /**
   * Batch update multiple tokens
   * @param {object} updates - Map of path → value
   */
  batchUpdate(updates) {
    let changed = false;

    for (const [path, value] of Object.entries(updates)) {
      if (this.updateToken(path, value)) {
        changed = true;
      }
    }

    if (changed) {
      this.injectIntoDOM();
    }
  }

  /**
   * Export theme as JSON
   * @returns {string} JSON string
   */
  exportJSON() {
    return JSON.stringify(this.theme, null, 2);
  }

  /**
   * Export as CSS file
   * @returns {string} CSS code
   */
  exportCSS() {
    return this.generateCSS();
  }

  /**
   * Export as Tailwind config
   * @returns {string} JavaScript module code
   */
  exportTailwindConfig() {
    const config = {
      darkMode: 'class',
      theme: {
        extend: {
          colors: {},
          spacing: {},
          fontSize: {},
          fontFamily: {},
          fontWeight: {},
          lineHeight: {},
          letterSpacing: {},
          borderRadius: {},
          boxShadow: {}
        }
      }
    };

    // Helper to set nested object property
    const setNested = (obj, path, value) => {
      const keys = path;
      let current = obj;

      for (let i = 0; i < keys.length - 1; i++) {
        if (!current[keys[i]]) current[keys[i]] = {};
        current = current[keys[i]];
      }

      current[keys[keys.length - 1]] = value;
    };

    // Process color tokens
    const colorTokens = this.flattenTokens(this.theme.tokens.color || {});
    for (const [cssVar, value] of Object.entries(colorTokens)) {
      const path = cssVar.replace('--color-', '').split('-');

      // Use CSS variable reference for runtime theming
      setNested(config.theme.extend.colors, path, `rgb(var(${cssVar}))`);
    }

    // Process spacing tokens
    const spacingTokens = this.flattenTokens(this.theme.tokens.spacing || {});
    for (const [cssVar, value] of Object.entries(spacingTokens)) {
      const path = cssVar.replace('--spacing-', '').split('-');
      setNested(config.theme.extend.spacing, path, `var(${cssVar})`);
    }

    // Process typography tokens
    if (this.theme.tokens.typography) {
      const fontFamily = this.flattenTokens(this.theme.tokens.typography['font-family'] || {});
      for (const [cssVar, value] of Object.entries(fontFamily)) {
        const name = cssVar.replace('--typography-font-family-', '');
        config.theme.extend.fontFamily[name] = `var(${cssVar})`;
      }

      const fontSize = this.flattenTokens(this.theme.tokens.typography['font-size'] || {});
      for (const [cssVar, value] of Object.entries(fontSize)) {
        const name = cssVar.replace('--typography-font-size-', '');
        config.theme.extend.fontSize[name] = `var(${cssVar})`;
      }
    }

    // Process effects
    if (this.theme.tokens.effects) {
      const shadows = this.flattenTokens(this.theme.tokens.effects.shadow || {});
      for (const [cssVar, value] of Object.entries(shadows)) {
        const name = cssVar.replace('--effects-shadow-', '');
        config.theme.extend.boxShadow[name] = `var(${cssVar})`;
      }

      const radii = this.flattenTokens(this.theme.tokens.effects['border-radius'] || {});
      for (const [cssVar, value] of Object.entries(radii)) {
        const name = cssVar.replace('--effects-border-radius-', '');
        config.theme.extend.borderRadius[name] = `var(${cssVar})`;
      }
    }

    return `/** @type {import('tailwindcss').Config} */\nmodule.exports = ${JSON.stringify(config, null, 2)}`;
  }

  /**
   * Load theme from JSON string or object
   * @param {string|object} data - Theme data
   */
  loadTheme(data) {
    if (typeof data === 'string') {
      try {
        this.theme = JSON.parse(data);
      } catch (e) {
        console.error('Failed to parse theme JSON:', e);
        return false;
      }
    } else {
      this.theme = data;
    }

    this.injectIntoDOM();
    return true;
  }

  /**
   * Merge a partial theme (e.g., preset) with current theme
   * @param {object} partial - Partial theme object
   */
  mergeTheme(partial) {
    this.theme = this._deepMerge(this.theme, partial);
    this.injectIntoDOM();
  }

  /**
   * Deep merge utility
   * @private
   */
  _deepMerge(target, source) {
    const output = { ...target };

    if (this._isObject(target) && this._isObject(source)) {
      Object.keys(source).forEach(key => {
        if (this._isObject(source[key])) {
          if (!(key in target)) {
            output[key] = source[key];
          } else {
            output[key] = this._deepMerge(target[key], source[key]);
          }
        } else {
          output[key] = source[key];
        }
      });
    }

    return output;
  }

  /**
   * Check if value is plain object
   * @private
   */
  _isObject(item) {
    return item && typeof item === 'object' && !Array.isArray(item);
  }

  /**
   * Get all CSS variable names
   * @returns {string[]} Array of CSS variable names
   */
  getAllVariableNames() {
    const tokens = this.flattenTokens(this.theme.tokens);
    return Object.keys(tokens);
  }

  /**
   * Get computed value of a CSS variable from DOM
   * @param {string} varName - CSS variable name (with or without --)
   * @returns {string} Computed value
   */
  getComputedValue(varName) {
    if (!varName.startsWith('--')) {
      varName = `--${varName}`;
    }

    return getComputedStyle(document.documentElement).getPropertyValue(varName).trim();
  }

  /**
   * Save current theme to localStorage
   * @param {string} key - Storage key
   */
  saveToLocalStorage(key = 'customTheme') {
    try {
      localStorage.setItem(key, this.exportJSON());
      localStorage.setItem('themeMode', this.mode);
      console.log('Theme saved to localStorage');
      return true;
    } catch (e) {
      console.error('Failed to save theme:', e);
      return false;
    }
  }

  /**
   * Load theme from localStorage
   * @param {string} key - Storage key
   */
  loadFromLocalStorage(key = 'customTheme') {
    try {
      const data = localStorage.getItem(key);
      const savedMode = localStorage.getItem('themeMode');

      if (data) {
        this.loadTheme(data);
        if (savedMode) {
          this.setMode(savedMode);
        }
        console.log('Theme loaded from localStorage');
        return true;
      }
    } catch (e) {
      console.error('Failed to load theme:', e);
    }

    return false;
  }
}

// Auto-initialize if theme.json is available
(function autoInit() {
  if (typeof window !== 'undefined') {
    window.TokenEngine = TokenEngine;

    // Try to load theme.json automatically
    const themeJsonPath = window.THEME_JSON_PATH || 'theme.json';

    fetch(themeJsonPath)
      .then(response => response.json())
      .then(themeData => {
        window.themeEngine = new TokenEngine(themeData);

        // Check for saved mode
        const savedMode = localStorage.getItem('themeMode') || 'light';
        window.themeEngine.setMode(savedMode);

        // Dispatch event for listeners
        window.dispatchEvent(new CustomEvent('themeEngineReady', {
          detail: { engine: window.themeEngine }
        }));

        console.log('🎨 TokenEngine initialized and ready');
      })
      .catch(error => {
        console.warn('TokenEngine: Could not auto-load theme.json. Initialize manually.', error);
      });
  }
})();
